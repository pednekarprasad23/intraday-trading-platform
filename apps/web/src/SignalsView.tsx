import { useEffect, useState } from 'react';
import { research, type ResearchSignal } from './api';

function time(value: string | null) {
  if (!value) return '—';
  try {
    return new Date(value).toLocaleString();
  } catch {
    return value;
  }
}

function qualityBadge(quality: string) {
  const bg = quality === 'HIGH' ? '#e6f7f3' : quality === 'LOW' ? '#fef0ee' : '#fff8e6';
  const color = quality === 'HIGH' ? '#126756' : quality === 'LOW' ? '#9a392a' : '#8a6d00';
  return <span style={{ padding: '2px 8px', borderRadius: '4px', background: bg, color, fontSize: '0.72rem', fontWeight: 700 }}>{quality}</span>;
}

export function SignalsView() {
  const [signals, setSignals] = useState<ResearchSignal[]>([]);
  const [total, setTotal] = useState(0);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  async function loadSignals() {
    try {
      setLoading(true);
      setError(null);
      const res = await research.signals(0);
      setSignals(res.items || []);
      setTotal(res.total || 0);
    } catch (err: any) {
      setError(err?.message || 'Failed to load research signals');
    } finally {
      setLoading(false);
    }
  }

  useEffect(() => {
    void loadSignals();
  }, []);

  return (
    <div className="view-container" style={{ display: 'flex', flexDirection: 'column', gap: '20px' }}>
      <div className="section-heading" style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
        <div>
          <h2>Research Signals Stream</h2>
          <p className="muted">Persistent decision signals generated by historical strategies ({total} total recorded).</p>
        </div>
        <button className="quiet-button" onClick={() => void loadSignals()} disabled={loading}>
          {loading ? 'Refreshing…' : 'Refresh Signals'}
        </button>
      </div>

      {error && <p role="alert" className="error">Signals error: {error}</p>}

      <section style={{ background: '#fff', padding: '16px', border: '1px solid #d4dde4', borderRadius: '8px' }}>
        {signals.length === 0 && !loading ? (
          <p className="muted" style={{ padding: '40px 0', textAlign: 'center' }}>No research signals recorded.</p>
        ) : (
          <div className="table-wrap">
            <table>
              <thead>
                <tr>
                  <th>Decision Time</th>
                  <th>Strategy Version</th>
                  <th>Instrument ID</th>
                  <th>Direction</th>
                  <th>Quality</th>
                  <th>Provider</th>
                  <th>Partition</th>
                </tr>
              </thead>
              <tbody>
                {signals.map(sig => (
                  <tr key={sig.id}>
                    <td>{time(sig.decision_time)}</td>
                    <td><code>{sig.strategy_version_id}</code></td>
                    <td><code>{sig.instrument_id}</code></td>
                    <td>
                      <span style={{ fontWeight: 700, color: sig.direction === 'BUY' ? '#126756' : '#9a392a' }}>
                        {sig.direction}
                      </span>
                    </td>
                    <td>{qualityBadge(sig.quality)}</td>
                    <td>{sig.provider}</td>
                    <td><code style={{ fontSize: '0.75rem' }}>{sig.partition_id.substring(0, 12)}…</code></td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </section>
    </div>
  );
}
