class DhanClient:
    """HTTP client for Dhan v2 API."""

    def __init__(self):
        self._token: str | None = None
        self._ctx = ssl.create_default_context()
        self._last_token_load: float = 0
        self._cache: dict[str, tuple[float, Any]] = {}
        self._cache_ttl: float = 5.0  # 5s cache for quotes

    def _get_token(self) -> str:
        if self._token is None or time.time() - self._last_token_load > 3600:
            with SessionLocal() as db:
                key_path = Path(get_settings().credential_key_path)
                self._token = load_dhan_token(db, key_path)
            self._last_token_load = time.time()
        return self._token

    def _request(self, method: str, path: str, body: dict | None = None) -> dict:
        token = self._get_token()
        conn = http.client.HTTPSConnection("api.dhan.co", context=self._ctx)
        headers = {"access-token": token}
        if body is not None:
            headers["Content-Type"] = "application/json"
        conn.request(method, path, json.dumps(body), headers)
        resp = conn.getresponse()
        raw = resp.read().decode()
        conn.close()
        if resp.status >= 400:
            try:
                err = json.loads(raw)
                raise RuntimeError(f"Dhan API {resp.status}: {err}")
            except json.JSONDecodeError:
                raise RuntimeError(f"Dhan API {resp.status}: {raw[:200]}")
        try:
            return json.loads(raw) if raw else {}
        except json.JSONDecodeError:
            return {}

    def get_intraday_candles(
        self,
        security_id: int,
        exchange_segment: str,
        instrument: str,
        interval: str = "1",
        days: int = 5,
    ) -> list[Candle]:
        """Fetch intraday candles for a security.

        Args:
            security_id: Dhan security ID
            exchange_segment: NSE_EQ, IDX_I, etc.
            instrument: EQUITY, INDEX, etc.
            interval: 1, 5, 15, 25, 60 (minutes)
            days: number of trading days to fetch

        Returns:
            List of Candle objects
        """
        now = datetime.now(timezone.utc)
        start_date = (now.replace(hour=0, minute=0, second=0, microsecond=0) - __import__("datetime").timedelta(days=days)).strftime("%Y-%m-%d")
        end_date = now.strftime("%Y-%m-%d")

        data = self._request("POST", "/v2/charts/intraday", {
            "securityId": str(security_id),
            "exchangeSegment": exchange_segment,
            "instrument": instrument,
            "interval": interval,
            "fromDate": start_date,
            "toDate": end_date,
        })

        candles = []
        ts_list = data.get("timestamp", [])
        for i in range(len(ts_list)):
            ts_sec = ts_list[i]
            # Dhan uses epoch seconds
            ts = datetime.fromtimestamp(ts_sec, tz=timezone.utc)
            candles.append(Candle(
                timestamp=ts,
                open=data["open"][i] if i < len(data.get("open", [])) else 0,
                high=data["high"][i] if i < len(data.get("high", [])) else 0,
                low=data["low"][i] if i < len(data.get("low", [])) else 0,
                close=data["close"][i] if i < len(data.get("close", [])) else 0,
                volume=data["volume"][i] if i < len(data.get("volume", [])) else 0,
            ))

        return candles

    def get_historical_candles(
        self,
        security_id: int,
        exchange_segment: str,
        instrument: str,
        days: int = 30,
    ) -> list[Candle]:
        """Fetch daily historical candles."""
        now = datetime.now(timezone.utc)
        start_date = (now - __import__("datetime").timedelta(days=days)).strftime("%Y-%m-%d")
        end_date = now.strftime("%Y-%m-%d")

        data = self._request("POST", "/v2/charts/historical", {
            "securityId": str(security_id),
            "exchangeSegment": exchange_segment,
            "instrument": instrument,
            "fromDate": start_date,
            "toDate": end_date,
        })

        candles = []
        ts_list = data.get("timestamp", [])
        for i in range(len(ts_list)):
            ts_sec = ts_list[i]
            ts = datetime.fromtimestamp(ts_sec, tz=timezone.utc)
            candles.append(Candle(
                timestamp=ts,
                open=data["open"][i] if i < len(data.get("open", [])) else 0,
                high=data["high"][i] if i < len(data.get("high", [])) else 0,
                low=data["low"][i] if i < len(data.get("low", [])) else 0,
                close=data["close"][i] if i < len(data.get("close", [])) else 0,
                volume=data["volume"][i] if i < len(data.get("volume", [])) else 0,
            ))

        return candles

    def get_quote(self, security_id: int, symbol: str) -> Quote:
        """Get a recent quote from the last candle."""
        candles = self.get_intraday_candles(security_id, "NSE_EQ", "EQUITY", interval="1", days=1)
        if not candles:
            return Quote(
                symbol=symbol,
                security_id=security_id,
                last_price=0,
                high=0,
                low=0,
                volume=0,
                timestamp=datetime.now(timezone.utc),
            )
        last = candles[-1]
        # Get session high/low
        highs = [c.high for c in candles if c.high > 0]
        lows = [c.low for c in candles if c.low > 0]
        total_vol = sum(c.volume for c in candles)
        return Quote(
            symbol=symbol,
            security_id=security_id,
            last_price=last.close,
            high=max(highs) if highs else last.high,
            low=min(lows) if lows else last.low,
            volume=total_vol,
            timestamp=last.timestamp,
        )


