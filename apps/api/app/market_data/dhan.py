def get_instrument_security_id(db: SessionLocal, canonical_symbol: str) -> tuple[int, str, str] | None:
    """Get security ID and metadata for a canonical symbol.

    Returns:
        (security_id, exchange_segment, instrument) or None
    """
    inst = db.scalar(select(Instrument).where(Instrument.canonical_symbol == canonical_symbol))
    if inst is None:
        return None

    ps = db.scalar(select(ProviderSymbol).where(
        ProviderSymbol.instrument_id == inst.id,
        ProviderSymbol.provider == "DHAN",
    ))
    if ps is None:
        return None

    try:
        sec_id = int(ps.provider_instrument_key)
    except (ValueError, TypeError):
        return None

    # Map exchange segment and instrument type
    if inst.asset_class == "INDEX":
        return sec_id, "IDX_I", "INDEX"
    elif inst.asset_class == "EQUITY":
        return sec_id, "NSE_EQ", "EQUITY"
    elif inst.asset_class == "FUTURES":
        return sec_id, "NSE_FNO", "FUTSTK"
    return None


