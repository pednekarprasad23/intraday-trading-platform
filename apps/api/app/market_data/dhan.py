# Public router for market data (no auth required)
public_router = APIRouter(prefix="/api/v1/dhan")

# Authenticated router for order execution
router = APIRouter(prefix="/api/v1/dhan", dependencies=[Depends(require_user)])


class CandleResponse(BaseModel):
    """Single candle."""
    timestamp: datetime
    open: float
    high: float
    low: float
    close: float
    volume: float


class QuoteResponse(BaseModel):
    """Quote response."""
    symbol: str
    security_id: int
    last_price: float
    high: float
    low: float
    volume: float
    timestamp: datetime


class SignalResponse(BaseModel):
    """Signal response."""
    symbol: str
    timestamp: datetime
    direction: str
    strength: str
    reason: str
    indicators: dict[str, Any] = Field(default_factory=dict)


class SignalsResponse(BaseModel):
    """Signals response."""
    symbol: str
    signals: list[SignalResponse]
    candles_count: int


class MarketDataResponse(BaseModel):
    """Combined market data for an instrument."""
    symbol: str
    quote: QuoteResponse
    signals: list[SignalResponse]
    candles: list[CandleResponse]
    order_blocks: list[dict]


@router.get("/quotes/{symbol}", response_model=QuoteResponse)
def get_quote(symbol: str):
    """Get live quote for a symbol."""
    client = get_dhan_client()
    with SessionLocal() as db:
        result = get_instrument_security_id(db, symbol.upper())
        if result is None:
            return QuoteResponse(
                symbol=symbol, security_id=0, last_price=0,
                high=0, low=0, volume=0, timestamp=datetime.now(timezone.utc),
            )
        sec_id, seg, inst = result
    quote = client.get_quote(sec_id, symbol.upper())
    return QuoteResponse(
        symbol=quote.symbol,
        security_id=quote.security_id,
        last_price=quote.last_price,
        high=quote.high,
        low=quote.low,
        volume=quote.volume,
        timestamp=quote.timestamp,
    )


@router.get("/candles/{symbol}", response_model=list[CandleResponse])
def get_candles(
    symbol: str,
    interval: str = Query("1", description="Candle interval in minutes"),
    days: int = Query(5, ge=1, le=30, description="Number of days"),
):
    """Get intraday candles for a symbol."""
    client = get_dhan_client()
    with SessionLocal() as db:
        result = get_instrument_security_id(db, symbol.upper())
        if result is None:
            return []
        sec_id, seg, inst = result
    candles = client.get_intraday_candles(sec_id, seg, inst, interval=interval, days=days)
    return [
        CandleResponse(
            timestamp=c.timestamp,
            open=c.open,
            high=c.high,
            low=c.low,
            close=c.close,
            volume=c.volume,
        )
        for c in candles
    ]


@router.get("/signals/{symbol}", response_model=SignalsResponse)
def get_signals(symbol: str):
    """Generate trading signals for a symbol."""
    client = get_dhan_client()
    with SessionLocal() as db:
        result = get_instrument_security_id(db, symbol.upper())
        if result is None:
            return SignalsResponse(symbol=symbol, signals=[], candles_count=0)
        sec_id, seg, inst = result
    candles = client.get_intraday_candles(sec_id, seg, inst, interval="1", days=5)
    signals = generate_signals(candles, symbol.upper(), client)
    return SignalsResponse(
        symbol=symbol,
        signals=[
            SignalResponse(
                timestamp=s.timestamp,
                direction=s.direction,
                strength=s.strength,
                reason=s.reason,
                indicators=s.indicators,
            )
            for s in signals
        ],
        candles_count=len(candles),
    )


@router.get("/market-data/{symbol}", response_model=MarketDataResponse)
def get_market_data(symbol: str):
    """Get complete market data: quote, signals, candles, order blocks."""
    client = get_dhan_client()
    with SessionLocal() as db:
        result = get_instrument_security_id(db, symbol.upper())
        if result is None:
            return MarketDataResponse(
                symbol=symbol,
                quote=QuoteResponse(
                    symbol=symbol, security_id=0, last_price=0,
                    high=0, low=0, volume=0, timestamp=datetime.now(timezone.utc),
                ),
                signals=[],
                candles=[],
                order_blocks=[],
            )
        sec_id, seg, inst = result

    # Get quote
    quote = client.get_quote(sec_id, symbol.upper())

    # Get candles and generate signals
    candles = client.get_intraday_candles(sec_id, seg, inst, interval="5", days=5)
    signals = generate_signals(candles, symbol.upper(), client)
    order_blocks = detect_order_blocks(candles)

    return MarketDataResponse(
        symbol=symbol,
        quote=QuoteResponse(
            symbol=quote.symbol,
            security_id=quote.security_id,
            last_price=quote.last_price,
            high=quote.high,
            low=quote.low,
            volume=quote.volume,
            timestamp=quote.timestamp,
        ),
        signals=[
            SignalResponse(
                timestamp=s.timestamp,
                direction=s.direction,
                strength=s.strength,
                reason=s.reason,
                indicators=s.indicators,
            )
            for s in signals
        ],
        candles=[
            CandleResponse(
                timestamp=c.timestamp,
                open=c.open,
                high=c.high,
                low=c.low,
                close=c.close,
                volume=c.volume,
            )
            for c in candles
        ],
        order_blocks=order_blocks,
    )
