def compute_ema(values: list[float], period: int) -> list[float]:
    """Compute EMA for a list of values."""
    if len(values) < period:
        return values
    ema = [0.0] * len(values)
    multiplier = 2 / (period + 1)
    # Seed with SMA
    ema[period - 1] = sum(values[:period]) / period
    for i in range(period, len(values)):
        ema[i] = (values[i] - ema[i - 1]) * multiplier + ema[i - 1]
    return ema


def compute_rsi(closes: list[float], period: int = 14) -> float:
    """Compute RSI from closing prices."""
    if len(closes) < period + 1:
        return 50.0
    deltas = [closes[i] - closes[i - 1] for i in range(1, len(closes))]
    gains = [d if d > 0 else 0 for d in deltas[-period:]]
    losses = [-d if d < 0 else 0 for d in deltas[-period:]]
    avg_gain = sum(gains) / period
    avg_loss = sum(losses) / period
    if avg_loss == 0:
        return 100.0
    rs = avg_gain / avg_loss
    return 100 - (100 / (1 + rs))


def compute_sma(values: list[float], period: int) -> float:
    """Compute simple moving average."""
    if len(values) < period:
        return sum(values) / len(values) if values else 0
    return sum(values[-period:]) / period


def detect_order_blocks(candles: list[Candle], threshold_pct: float = 0.5) -> list[dict]:
    """Detect order blocks — zones where price consolidated before a big move.

    An order block is a range of candles where:
    - Body size is small (consolidation)
    - Followed by a large body (breakout)
    """
    if len(candles) < 5:
        return []

    order_blocks = []
    avg_body = sum(abs(c.close - c.open) for c in candles) / len(candles)

    for i in range(len(candles) - 2):
        curr = candles[i]
        next_candle = candles[i + 1]

        curr_body = abs(curr.close - curr.open)
        next_body = abs(next_candle.close - next_candle.open)

        # Small body followed by large body (3x average)
        if curr_body < avg_body * 0.5 and next_body > avg_body * 2:
            direction = "bullish" if next_candle.close > next_candle.open else "bearish"
            order_blocks.append({
                "type": direction,
                "low": min(curr.low, next_candle.low),
                "high": max(curr.high, next_candle.high),
                "price_range": [min(curr.low, next_candle.low), max(curr.high, next_candle.high)],
                "strength": "strong" if next_body > avg_body * 3 else "moderate",
            })

    # Return the most recent 3 order blocks
    return order_blocks[-3:]


def generate_signals(
    candles: list[Candle],
    symbol: str,
    client: DhanClient | None = None,
) -> list[Signal]:
    """Generate trading signals from candle data.

    Analyzes:
    - EMA crossovers (9/21)
    - RSI levels
    - MACD-like momentum
    - Order blocks
    - Volume profile
    """
    if len(candles) < 30:
        return [Signal(
            symbol=symbol,
            timestamp=datetime.now(timezone.utc),
            direction="NEUTRAL",
            strength="WEAK",
            reason=f"Insufficient data ({len(candles)} candles)",
        )]

    closes = [c.close for c in candles]
    volumes = [c.volume for c in candles]
    highs = [c.high for c in candles]
    lows = [c.low for c in candles]

    # EMA calculations
    ema9 = compute_ema(closes, 9)
    ema21 = compute_ema(closes, 21)
    ema50 = compute_ema(closes, 50)

    # RSI
    rsi = compute_rsi(closes, 14)

    # SMA for volume
    avg_vol = compute_sma(volumes, 20)
    last_vol = volumes[-1] if volumes else 0

    # Momentum (rate of change)
    roc = (closes[-1] - closes[-5]) / closes[-5] * 100 if closes[-5] else 0

    # Signals
    signals = []

    # 1. EMA crossover signal
    if len(ema9) >= 2 and len(ema21) >= 2:
        prev_ema9 = ema9[-2]
        prev_ema21 = ema21[-2]
        curr_ema9 = ema9[-1]
        curr_ema21 = ema21[-1]

        if prev_ema9 <= prev_ema21 and curr_ema9 > curr_ema21:
            signals.append(Signal(
                symbol=symbol,
                timestamp=candles[-1].timestamp,
                direction="BUY",
                strength="STRONG",
                reason="EMA 9/21 golden cross",
                indicators={"ema9": round(curr_ema9, 2), "ema21": round(curr_ema21, 2)},
            ))
        elif prev_ema9 >= prev_ema21 and curr_ema9 < curr_ema21:
            signals.append(Signal(
                symbol=symbol,
                timestamp=candles[-1].timestamp,
                direction="SELL",
                strength="STRONG",
                reason="EMA 9/21 death cross",
                indicators={"ema9": round(curr_ema9, 2), "ema21": round(curr_ema21, 2)},
            ))

    # 2. RSI signal
    if rsi < 30:
        signals.append(Signal(
            symbol=symbol,
            timestamp=candles[-1].timestamp,
            direction="BUY",
            strength="MODERATE",
            reason=f"RSI oversold ({rsi:.1f})",
            indicators={"rsi": round(rsi, 1)},
        ))
    elif rsi > 70:
        signals.append(Signal(
            symbol=symbol,
            timestamp=candles[-1].timestamp,
            direction="SELL",
            strength="MODERATE",
            reason=f"RSI overbought ({rsi:.1f})",
            indicators={"rsi": round(rsi, 1)},
        ))

    # 3. Volume signal
    if last_vol > avg_vol * 1.5:
        direction = "BUY" if closes[-1] > closes[-2] else "SELL"
        signals.append(Signal(
            symbol=symbol,
            timestamp=candles[-1].timestamp,
            direction=direction,
            strength="MODERATE",
            reason=f"High volume ({last_vol/avg_vol:.1f}x avg)",
            indicators={"volume_ratio": round(last_vol / avg_vol, 1)},
        ))

    # 4. Order blocks
    order_blocks = detect_order_blocks(candles)
    if order_blocks:
        last_price = closes[-1]
        for ob in order_blocks:
            if ob["type"] == "bullish" and ob["low"] <= last_price <= ob["high"]:
                signals.append(Signal(
                    symbol=symbol,
                    timestamp=candles[-1].timestamp,
                    direction="BUY",
                    strength=ob["strength"].upper(),
                    reason=f"Bullish order block support at {ob['low']:.2f}-{ob['high']:.2f}",
                    indicators={"order_block": ob["price_range"]},
                ))
            elif ob["type"] == "bearish" and ob["low"] <= last_price <= ob["high"]:
                signals.append(Signal(
                    symbol=symbol,
                    timestamp=candles[-1].timestamp,
                    direction="SELL",
                    strength=ob["strength"].upper(),
                    reason=f"Bearish order block resistance at {ob['low']:.2f}-{ob['high']:.2f}",
                    indicators={"order_block": ob["price_range"]},
                ))

    # 5. Trend signal (price vs EMAs)
    last_price = closes[-1]
    if len(ema50) >= 1 and ema50[-1] > 0:
        if last_price > ema50[-1] and len(ema9) >= 1 and ema9[-1] > ema21[-1] if len(ema21) >= 1 else True:
            signals.append(Signal(
                symbol=symbol,
                timestamp=candles[-1].timestamp,
                direction="BUY",
                strength="WEAK",
                reason="Price above EMA 50, bullish trend",
                indicators={"price": round(last_price, 2), "ema50": round(ema50[-1], 2)},
            ))
        elif last_price < ema50[-1] and len(ema9) >= 1 and ema9[-1] < ema21[-1] if len(ema21) >= 1 else True:
            signals.append(Signal(
                symbol=symbol,
                timestamp=candles[-1].timestamp,
                direction="SELL",
                strength="WEAK",
                reason="Price below EMA 50, bearish trend",
                indicators={"price": round(last_price, 2), "ema50": round(ema50[-1], 2)},
            ))

    # Aggregate to a single signal
    if not signals:
        return [Signal(
            symbol=symbol,
            timestamp=datetime.now(timezone.utc),
            direction="NEUTRAL",
            strength="WEAK",
            reason="No clear signal",
            indicators={
                "rsi": round(rsi, 1),
                "roc": round(roc, 2),
                "ema9": round(ema9[-1], 2) if ema9 else 0,
                "ema21": round(ema21[-1], 2) if ema21 else 0,
                "ema50": round(ema50[-1], 2) if ema50 else 0,
            },
        )]

    # Count buy vs sell signals
    buy_count = sum(1 for s in signals if s.direction == "BUY")
    sell_count = sum(1 for s in signals if s.direction == "SELL")

    if buy_count > sell_count:
        max_strength = max(signals, key=lambda s: {"STRONG": 3, "MODERATE": 2, "WEAK": 1}.get(s.strength, 0))
        agg_indicators = {}
        for s in signals:
            agg_indicators.update(s.indicators)
        return [Signal(
            symbol=symbol,
            timestamp=datetime.now(timezone.utc),
            direction="BUY",
            strength=max_strength.strength,
            reason=f"{buy_count} buy vs {sell_count} sell signals",
            indicators=agg_indicators,
        )]
    elif sell_count > buy_count:
        max_strength = max(signals, key=lambda s: {"STRONG": 3, "MODERATE": 2, "WEAK": 1}.get(s.strength, 0))
        agg_indicators = {}
        for s in signals:
            agg_indicators.update(s.indicators)
        return [Signal(
            symbol=symbol,
            timestamp=datetime.now(timezone.utc),
            direction="SELL",
            strength=max_strength.strength,
            reason=f"{sell_count} sell vs {buy_count} buy signals",
            indicators=agg_indicators,
        )]
    else:
        return [Signal(
            symbol=symbol,
            timestamp=datetime.now(timezone.utc),
            direction="NEUTRAL",
            strength="MODERATE",
            reason=f"Balanced: {buy_count} buy, {sell_count} sell",
            indicators={"rsi": round(rsi, 1)},
        )]


